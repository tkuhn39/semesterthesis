# --- §7.3, §7.4 tooth thickness allowances and generating profile shift ------------------------


@eq(SOURCE, "(118)", section="7.3", page=65)
@eq(SOURCE, "(119)", section="7.3", page=65)
def tooth_thickness_limit(s_n_mm: float, tooth_thickness_allowance_um: float) -> float:
    """Upper or lower limit of the normal tooth thickness: s_ns = s_n + E_sns, s_ni = s_n + E_sni.

    The allowance is given in micrometres like the contract; the result is in millimetres.
    """
    s_n = finite_input(s_n_mm, "normal tooth thickness s_n")
    allowance = finite_input(tooth_thickness_allowance_um, "tooth thickness allowance E_sn")
    return finite_result(s_n + 1.0e-3 * allowance, "tooth thickness limit")


@eq(SOURCE, "(123)", section="7.4", page=67)
@eq(SOURCE, "(124)", section="7.4", page=67)
@eq(OLD, "(3.6.03)", section="3.6.3", page=14, note="with q = 0; A_s of DIN 3960 is E_sn")
def generating_profile_shift_coefficient(
    x: float, m_n_mm: float, alpha_n_rad: float, tooth_thickness_allowance_um: float
) -> float:
    """Generating profile shift coefficient of a finished gear (q = 0):
    x_E = x + E_sn / (2 m_n tan(alpha_n)).

    Eq. (123) with the upper allowance E_sns gives x_Es, Eq. (124) with the lower allowance E_sni
    gives x_Ei. The allowance is the normal tooth thickness allowance in micrometres.
    """
    shift = finite_input(x, "profile shift coefficient x")
    m_n = positive_input(m_n_mm, "normal module m_n")
    alpha_n = pressure_angle(alpha_n_rad, "normal pressure angle alpha_n")
    allowance = 1.0e-3 * finite_input(
        tooth_thickness_allowance_um, "tooth thickness allowance E_sn"
    )
    return finite_result(
        shift
        + safe_div(allowance, 2.0 * m_n * math.tan(alpha_n), what="E_sn / (2 m_n tan alpha_n)"),
        "generating profile shift coefficient x_E",
    )


@eq(
    SOURCE,
    "(120)",
    section="7.4",
    page=67,
    note="q_max = q_min = q: one allowance of the pre-machining tool",
)
@eq(SOURCE, "(121)", section="7.4", page=67)
@eq(OLD, "(3.6.03)", section="3.6.3", page=14, note="term q / sin(alpha_n)")
def pre_machining_generating_profile_shift_coefficient(
    x_E: float, m_n_mm: float, alpha_n_rad: float, q_mm: float
) -> float:
    """Generating profile shift coefficient of the pre-machining tool that leaves the machining
    allowance q per flank: x_EV = x_E + q / (m_n sin(alpha_n)).

    Eq. (120) and (121) pair the limits (x_EsV with x_Ei and q_max, x_EiV with x_Es and q_min);
    with one allowance q of the tool both read as above. The root generated by the pre-machining
    tool and the flank finished at x_E give the gear of Bild 36 b).
    """
    shift = finite_input(x_E, "generating profile shift coefficient x_E")
    m_n = positive_input(m_n_mm, "normal module m_n")
    alpha_n = pressure_angle(alpha_n_rad, "normal pressure angle alpha_n")
    q = finite_input(q_mm, "machining allowance q")
    if q < 0.0:
        raise InputRangeError(f"machining allowance q must be >= 0, got {q_mm!r}")
    return finite_result(
        shift + safe_div(q, m_n * math.sin(alpha_n), what="q / (m_n sin alpha_n)"), "x_EV"
    )


