"""Tool-based generation of an external cylindrical gear by a rack-type tool.

Sources: DIN ISO 21771:2014-08 (ISO 21771:2007) §4.6 heights, §4.7 tooth thickness with x_E,
§7.1 tool reference profile, §7.3 tooth thickness allowances, §7.4 generating profile shift,
§7.5 generated root diameter, §7.6 form circles (Eq. (128) in the corrected form of Anhang NB,
p. 6), §7.7 undercut, §7.9 tip tooth thickness; DIN 3960:1987-03 Anhang A.3.1 for the tip form
circle generated by the edge break flank of the tool, which the current norm does not give; FVA
604 I (2012) for the straight part of the tool addendum. Every function realises one equation;
angles are radians (``_rad``), lengths millimetres (``_mm``), the allowance micrometres
(``_um``) like the contract. Formulas are written for external gears.

Which value of x_E. The allowances give two generating profile shift coefficients, x_Es at the
upper and x_Ei at the lower tooth thickness allowance (Eq. (123), (124); Bild 38 letters
d_fEs and d_fEi). The generation is evaluated at x_Es (the maximum-material tooth, as STplus
prints it) and reports x_Ei and d_fEi alongside. Without allowances x_E = x and the result says
so. §7.5 asks for the values of the finishing process: a machining allowance q of the tool
(Eq. (120), (121)) belongs to a pre-machining tool whose fillet is finished by a second tool; the
finishing tool is an extension point, so a tool with q > 0 is not supported here, nor is a tool
with a protuberance (DIN 3960 A.3.3) or a tool whose module or profile angle differs from the
gear's (generating gear with alpha_wt0, Bild 39 note).

Root form circle. Eq. (128) holds for a gear free of undercut. The undercut limit is Eq. (135):
x_E < x_Emin means that the straight part of the tool flank reaches beyond the tangent point T of
the line of action; the root form circle is then the intersection of the fillet with the
involute (§7.6, p. 70), found numerically in ``gearcore.trochoid``. Eq. (129)/(130) are kept as a
cross-check; as printed, Eq. (130) uses sin(alpha_t) inside the bracket where Anhang NB corrects
Eq. (128) to sin(alpha_n), so the two agree for spur gears only (finding of increment 3).

Tip form circle. A tip chamfer given as an input is defined by h_K and s_aK (§6.1.2, Bild 24):
d_Fa = d_a - 2 h_K (Eq. (127)). A tool with an edge break flank (angle alpha_kP from the height
h_FfP0 above the datum line, Bild 36 a)) generates a second involute at the tip; the tip form
circle is the intersection of the two involutes (DIN 3960 Eq. (A.3.06)), the residual tooth
thickness at the tip Eq. (A.3.05). The short trochoid of the corner of the tool profile between
the two involutes is not modelled, as in DIN 3960.

Tolerance at boundaries. ``EPS`` (relative) as in ``gearcore.pair``: a value of Eq. (128) whose
bracket is negative by rounding noise only is the base circle; the edge break involute reaches
the tip only if it is thinner there by more than rounding noise.
"""

