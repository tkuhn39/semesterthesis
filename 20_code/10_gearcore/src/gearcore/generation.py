@eq(
    SOURCE,
    "(128)",
    section="7.6",
    page=6,
    note="bracket h_aP0 - x_E m_n - rho_aP0 (1 - sin alpha_n) of Anhang NB without x_E m_n; Bild 36 a) p. 64",
)
@eq(FVA, "(4.36)", page=29)
@eq(
    FVA,
    "(4.37)",
    page=29,
    note="with f_pr = 0 (no protuberance): h_prP0 = rho_aP0 (1 - sin alpha_n0)",
)
def tool_tip_form_height(h_aP0_mm: float, rho_aP0_mm: float, alpha_n_rad: float) -> float:
    """Straight part of the tool addendum: h_FaP0 = h_aP0 - rho_aP0 (1 - sin(alpha_n)).

    The tip rounding of radius rho_aP0 touches the flank rho_aP0 (1 - sin alpha_n) above the tip
    line. A rounding that consumes the whole addendum leaves no straight flank
    (``GeometryInfeasibleError``).
    """
    h_aP0 = positive_input(h_aP0_mm, "tool addendum h_aP0")
    rho = finite_input(rho_aP0_mm, "tool tip radius rho_aP0")
    if rho < 0.0:
        raise InputRangeError(f"tool tip radius rho_aP0 must be >= 0, got {rho_aP0_mm!r}")
    alpha_n = pressure_angle(alpha_n_rad, "normal pressure angle alpha_n")
    height = finite_result(h_aP0 - rho * (1.0 - math.sin(alpha_n)), "h_FaP0")
    if height <= 0.0:
        raise GeometryInfeasibleError(
            f"tool tip radius rho_aP0 = {rho!r} leaves no straight flank on the tool addendum "
            f"h_aP0 = {h_aP0!r} (h_FaP0 = {height!r})"
        )
    return height


@eq(SOURCE, "(125)", section="7.5", page=68)
@eq(OLD, "(3.6.04)", section="3.6.4", page=14)
def generated_root_diameter(d_mm: float, x_E: float, m_n_mm: float, h_aP0_mm: float) -> float:
    """Root diameter generated by a rack-type tool: d_fE = d + 2 x_E m_n - 2 h_aP0."""
    d = positive_input(d_mm, "reference diameter d")
    shift = finite_input(x_E, "generating profile shift coefficient x_E")
    m_n = positive_input(m_n_mm, "normal module m_n")
    h_aP0 = positive_input(h_aP0_mm, "tool addendum h_aP0")
    d_fE = finite_result(d + 2.0 * shift * m_n - 2.0 * h_aP0, "generated root diameter d_fE")
    if d_fE <= 0.0:
        raise GeometryInfeasibleError(f"generated root diameter d_fE = {d_fE!r} is not positive")
    return d_fE


@eq(SOURCE, "(135)", section="7.7", page=70)
@eq(OLD, "(3.6.06)", section="3.6.6", page=14)
def min_generating_profile_shift_coefficient(
    h_FaP0_mm: float, m_n_mm: float, z: int, alpha_t_rad: float, beta_rad: float
) -> float:
    """Smallest generating profile shift coefficient free of undercut, for a rack-type tool
    without protuberance: x_Emin = h_FaP0 / m_n - z sin^2(alpha_t) / (2 cos(beta)).

    Below it the straight part of the tool flank reaches beyond the tangent point T of the line of
    action and the tip rounding cuts into the involute.
    """
    h_FaP0 = positive_input(h_FaP0_mm, "tool tip form height h_FaP0")
    m_n = positive_input(m_n_mm, "normal module m_n")
    number = teeth(z)
    alpha_t = pressure_angle(alpha_t_rad, "transverse pressure angle alpha_t")
    beta = helix(beta_rad)
    return finite_result(
        h_FaP0 / m_n - number * math.sin(alpha_t) ** 2 / (2.0 * math.cos(beta)), "x_Emin"
    )


@eq(
    SOURCE,
    "(128)",
    section="7.6",
    page=6,
    note="corrected form of Anhang NB: (1 - sin alpha_n) in the bracket; p. 69 prints (1 - sin alpha_t)",
)
@eq(OLD, "(3.6.08)", section="3.6.7", page=16)
@eq(FVA, "(4.35)", page=29)
def root_form_diameter(
    d_mm: float, alpha_t_rad: float, h_FaP0_mm: float, x_E: float, m_n_mm: float, d_b_mm: float
) -> float:
    """Root form diameter of a gear free of undercut, generated by a rack-type tool:
    d_Ff = sqrt((d sin(alpha_t) - 2 (h_FaP0 - x_E m_n) / sin(alpha_t))^2 + d_b^2),
    with the straight part of the tool addendum h_FaP0 = h_aP0 - rho_aP0 (1 - sin alpha_n).

    The bracket is the roll length from the tangent point T to the point generated by the end of
    the straight flank. A negative bracket means undercut: the equation does not apply and the
    root form circle follows from the intersection of the fillet with the involute
    (``GeometryInfeasibleError``; see ``compute_generation``). Within ``EPS`` d of zero the
    bracket is zero and d_Ff = d_b.
    """
    d = positive_input(d_mm, "reference diameter d")
    alpha_t = pressure_angle(alpha_t_rad, "transverse pressure angle alpha_t")
    h_FaP0 = positive_input(h_FaP0_mm, "tool tip form height h_FaP0")
    shift = finite_input(x_E, "generating profile shift coefficient x_E")
    m_n = positive_input(m_n_mm, "normal module m_n")
    d_b = positive_input(d_b_mm, "base diameter d_b")
    sine = math.sin(alpha_t)
    roll = finite_result(
        d * sine - safe_div(2.0 * (h_FaP0 - shift * m_n), sine, what="(128)"), "roll length"
    )
    if roll < -EPS * d:
        raise GeometryInfeasibleError(
            f"undercut: the straight flank of the tool reaches {-0.5 * roll!r} mm beyond the "
            "tangent point T; Eq. (128) does not apply, the root form circle is the intersection "
            "of the fillet with the involute"
        )
    return finite_result(math.hypot(max(roll, 0.0), d_b), "root form diameter d_Ff")


@eq(SOURCE, "(129)", section="7.6", page=69)
@eq(
    SOURCE,
    "(130)",
    section="7.6",
    page=69,
    note="as printed, with (1 - sin alpha_t): agrees with the corrected Eq. (128) for spur gears only",
)
@eq(OLD, "(3.6.09)", section="3.6.7", page=16)
@eq(OLD, "(3.6.10)", section="3.6.7", page=16, note="prints h*_FaP0 in place of the bracket")
def root_form_diameter_by_roll_angle(
    d_b_mm: float,
    z: int,
    alpha_t_rad: float,
    beta_rad: float,
    h_aP0_mm: float,
    rho_aP0_mm: float,
    m_n_mm: float,
    x_E: float,
) -> float:
    """Root form diameter by the roll angle at the root form circle, as printed:
    tan(alpha_Ff) = xi_Ff = xi_t - 4 [(h_aP0 - rho_aP0 (1 - sin alpha_t)) / m_n - x_E] cos(beta)
    / (z sin(2 alpha_t)), d_Ff = d_b / cos(alpha_Ff).

    Cross-check of Eq. (128) for spur gears. For helical gears the printed sine of alpha_t in the
    bracket differs from the corrected Eq. (128) of Anhang NB (sin alpha_n); this function keeps
    the printed form so that the difference can be shown. A negative roll angle means undercut
    (``GeometryInfeasibleError``).
    """
    d_b = positive_input(d_b_mm, "base diameter d_b")
    number = teeth(z)
    alpha_t = pressure_angle(alpha_t_rad, "transverse pressure angle alpha_t")
    beta = helix(beta_rad)
    h_aP0 = positive_input(h_aP0_mm, "tool addendum h_aP0")
    rho = finite_input(rho_aP0_mm, "tool tip radius rho_aP0")
    m_n = positive_input(m_n_mm, "normal module m_n")
    shift = finite_input(x_E, "generating profile shift coefficient x_E")
    bracket = (h_aP0 - rho * (1.0 - math.sin(alpha_t))) / m_n - shift
    xi = finite_result(
        math.tan(alpha_t) - 4.0 * bracket * math.cos(beta) / (number * math.sin(2.0 * alpha_t)),
        "roll angle xi_Ff",
    )
    if xi < -EPS:
        raise GeometryInfeasibleError(
            f"undercut: the roll angle at the root form circle xi_Ff = {xi!r} is negative"
        )
    return finite_result(d_b / math.cos(math.atan(max(xi, 0.0))), "root form diameter d_Ff")


# --- §7.6 tip form circle -------------------------------------------------------------------------


@eq(SOURCE, "(127)", section="7.6", page=68, note="solved for h_K")
def tip_chamfer_height(d_a_mm: float, d_Fa_mm: float) -> float:
    """Radial height of the tip chamfer from the tip form diameter: h_K = (d_a - d_Fa) / 2."""
    d_a = positive_input(d_a_mm, "tip diameter d_a")
    d_Fa = positive_input(d_Fa_mm, "tip form diameter d_Fa")
    if d_Fa > d_a * (1.0 + EPS):
        raise InputRangeError(f"tip form diameter {d_Fa!r} exceeds the tip diameter {d_a!r}")
    return max(0.5 * (d_a - d_Fa), 0.0)


